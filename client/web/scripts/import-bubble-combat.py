"""Import tactical resources from the user's local Bubble cache, with SHA checks.

No network, installer execution or generated artwork. The positional MessagePack
schema is read from Bubble TacticalTemplateData (index-BP60ZkRz.js).
"""
from pathlib import Path
import gzip
import hashlib
import json
import struct

ROOT = Path(__file__).resolve().parents[3]
CACHE = ROOT / 'bubble/BubbleGame'
DEST = ROOT / 'client/web/public/combat-assets'


class MessagePack:
    def __init__(self, data):
        self.data, self.pos = data, 0

    def take(self, n):
        b = self.data[self.pos:self.pos+n]
        if len(b) != n:
            raise ValueError('Truncated MessagePack')
        self.pos += n
        return b

    def integer(self, fmt):
        return struct.unpack('>' + fmt, self.take(struct.calcsize(fmt)))[0]

    def read(self):
        b = self.take(1)[0]
        if b <= 127: return b
        if b >= 224: return b - 256
        if 160 <= b <= 191: return self.take(b & 31).decode()
        if 144 <= b <= 159: return [self.read() for _ in range(b & 15)]
        if 128 <= b <= 143: return {self.read(): self.read() for _ in range(b & 15)}
        if b == 192: return None
        if b in (194, 195): return b == 195
        if b in (204, 205, 206, 207, 208, 209, 210, 211):
            return self.integer({204:'B',205:'H',206:'I',207:'Q',208:'b',209:'h',210:'i',211:'q'}[b])
        if b in (217, 218, 219): return self.take(self.integer({217:'B',218:'H',219:'I'}[b])).decode()
        if b in (220, 221): return [self.read() for _ in range(self.integer('H' if b == 220 else 'I'))]
        if b in (222, 223): return {self.read(): self.read() for _ in range(self.integer('H' if b == 222 else 'I'))}
        raise ValueError(f'Unsupported MessagePack tag {b}')


def main():
    entries = {}
    for p in CACHE.glob('sources/*/manifests/*/objects/*.json'):
        raw = p.read_bytes()
        if raw[:2] == b'\x1f\x8b': raw = gzip.decompress(raw)
        if b'data/tactical' not in raw: continue
        try: doc = json.loads(raw)
        except (ValueError, UnicodeError): continue
        entries.update({k: v for k, v in doc.get('assets', {}).items() if k.startswith('data/tactical')})
    provenance = {}

    def extract(path):
        entry = entries[path]
        carrier = entry['carrier']
        sha = carrier['packHash']
        with (CACHE / f'packs/sha256/{sha[:2]}/{sha}.pack').open('rb') as f:
            f.seek(carrier['offset'])
            raw = f.read(carrier['length'])
        if hashlib.sha256(raw).hexdigest() != entry['hash']:
            raise ValueError(f'Invalid SHA-256: {path}')
        provenance[path] = entry
        return raw

    data = gzip.decompress(extract('data/tactical_templates.bin'))
    parser = MessagePack(data)
    templates, maps = parser.read()
    assert parser.pos == len(data)
    DEST.mkdir(parents=True, exist_ok=True)
    available = {}
    for key, value in templates.items():
        path = f'data/tactical/{key}.webp'
        if path not in entries: continue
        try: raw = extract(path)
        except FileNotFoundError: continue
        (DEST / f'{key}.webp').write_bytes(raw)
        available[key] = value
    assert '1' in available, 'Default official template is required'
    (DEST / 'tactical.json').write_text(json.dumps({'templates': available, 'mapTemplates': maps}, separators=(',', ':')))
    (DEST / 'provenance.json').write_text(json.dumps(provenance, indent=2))
    # Preserve Bubble's classification, seeded variants and obstacle clipping.
    # Isolate pure geometry only: no application runtime or network code.
    with (ROOT / 'resources/app.asar').open('rb') as f:
        header = struct.unpack('<4I', f.read(16))
        tree = json.loads(f.read(header[3]))
        entry = tree['files']['dist']['files']['assets']['files']['index-BP60ZkRz.js']
        f.seek(8 + header[1] + int(entry['offset']))
        source = f.read(entry['size'])
    assert hashlib.sha256(source).hexdigest() == entry['integrity']['hash']
    text = source.decode()
    geometry = text[text.index('const it=14,wn=20;'):text.index('function Fr(s)')]
    generated = ('/* eslint-disable no-unused-vars, no-unused-expressions -- Unmodified generated Bubble geometry. */\n'
                 '// Generated by scripts/import-bubble-combat.py from Bubble index-BP60ZkRz.js.\n'
                 '// Pure source geometry; adapter declarations are in bubbleTacticalGeometry.d.ts.\n'
                 'const us=1,hs=16,ds=32,fs=2,Qs=560,D=21.5,z=43,ye=43,ee=86;\n'
                 + geometry.replace('}function ', '}\nfunction ').replace('}class ', '}\nclass ')
                 + '\nexport {kn as classifyTacticalCells, Pn as obstaclePolygons, Bn as TacticalRandom, rt as tacticalCellId, st as validTacticalPoint};\n')
    (ROOT / 'client/web/src/game/combat/bubbleTacticalGeometry.js').write_text(generated)
    print(f'{len(available)} tactical atlases, {len(maps)} map mappings, SHA-256 verified')


if __name__ == '__main__': main()
